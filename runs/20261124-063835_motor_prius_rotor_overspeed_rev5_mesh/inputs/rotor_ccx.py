"""Rotor lamination at overspeed (study 7): half a pole of an IPM rotor in plane stress, CalculiX.

Input: the pole exported from Pyleecan by models/motor/export_rotor_pole.py (pole axis on +x, mm).

1. write_geo: a Gmsh .geo (built-in kernel) of the half-pole sector, angle 0 to pi/poles, from the bore to the OD, with
   the magnet pocket cut out (it is open to the pole axis between the inner and outer apex). The pocket's outer edge
   is split at the end of the magnet seat so the seat's nodes are exactly the loaded ones. 6-node triangles, refined
   round the bridge (the thin steel between the pocket's end and the OD) by a distance field.
   with_pocket = False gives the plain annular sector, for the rotating-disk check.
2. write_deck: plane stress; symmetry on the pole axis (y = 0) and on the inter-pole line (angle pi/poles, through a
   *TRANSFORM so its normal can be fixed); the steel's centrifugal load (*DLOAD CENTRIF); the magnet carries no
   stiffness: its centrifugal force (density x area x stack x omega^2 x centroid radius) is applied as a uniform
   traction along the seat, with consistent nodal loads on the quadratic edges.

Traps carried over from the strap study (models/fea/strap_hole.py): CalculiX expands plane-stress elements into
one-layer wedges of the section thickness, so a thin layer is analysed (ANALYSIS_THICKNESS_MM) and the concentrated
magnet load is scaled by the same factor (body loads scale by themselves); numpy floats are cast before formatting;
the surface is traversed counter-clockwise (+z normal). New here: CalculiX 2.22 rejects numbers longer than about
21 characters in *CLOAD ("ERROR reading *CLOAD", found when a finer mesh made the loads smaller and their repr longer),
so loads are written with 13 significant digits.
Units: N, mm, tonne, s (density in t/mm^3, stress in MPa).
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

ANALYSIS_THICKNESS_MM = 0.01
TOL = 1e-6


def half_angle(geom: dict) -> float:
    return math.pi / int(geom["poles"])


def _seat_end(geom):
    s = geom["seat_half"]
    return s[2], s[3]


def write_geo(geom: dict, params: dict, path: Path, with_pocket: bool = True) -> None:
    Ri, Ro = float(geom["rotor_bore_radius_mm"]), float(geom["rotor_outer_radius_mm"])
    a = half_angle(geom)
    h_br, h_far = float(params["bridge_element_size_mm"]), float(params["far_element_size_mm"])
    pts, lines = [], []

    def P(x, y):
        pts.append((float(x), float(y)))
        return len(pts)

    def L(kind, i, j, c=None):
        lines.append((kind, i, j, c))
        return len(lines)

    O = P(0.0, 0.0)
    B0, O0 = P(Ri, 0.0), P(Ro, 0.0)
    O1, B1 = P(Ro * math.cos(a), Ro * math.sin(a)), P(Ri * math.cos(a), Ri * math.sin(a))
    refine = []
    if with_pocket:
        seg = geom["pocket_half"]
        sx, sy = _seat_end(geom)
        start = P(seg[0][1], seg[0][2])
        loop = [L("line", B0, start)]
        cur = start
        for s in seg:
            kind, x1, y1 = s[0], s[3], s[4]
            if s is seg[-1]:                      # the outer edge Z9 -> Z8: split at the seat's end (Z8c)
                mid = P(sx, sy)
                refine.append(L("line", cur, mid))
                loop.append(refine[-1])
                cur = mid
            nxt = P(x1, y1)
            loop.append(L("arc" if kind == "arc" else "line", cur, nxt, O if kind == "arc" else None))
            if kind == "arc" or s in seg[-3:-1] or s is seg[-1]:
                refine.append(loop[-1])
            cur = nxt
        loop += [L("line", cur, O0)]
    else:
        loop = [L("line", B0, O0)]
    od = L("arc", O0, O1, O)
    loop += [od, L("line", O1, B1), L("arc", B1, B0, O)]
    if not refine:
        refine = [od]
    out = ['// half a rotor pole, generated by models/fea/rotor_ccx.py']
    out += [f"Point({k}) = {{{x!r}, {y!r}, 0, {h_far!r}}};" for k, (x, y) in enumerate(pts, 1)]
    for k, (kind, i, j, c) in enumerate(lines, 1):
        out.append(f"Line({k}) = {{{i}, {j}}};" if kind == "line" else f"Circle({k}) = {{{i}, {c}, {j}}};")
    out.append(f"Curve Loop(1) = {{{', '.join(str(k) for k in loop)}}};")
    out.append("Plane Surface(1) = {1};")
    out.append(f"Field[1] = Distance; Field[1].CurvesList = {{{', '.join(str(k) for k in refine)}}}; "
               "Field[1].Sampling = 400;")
    out.append(f"Field[2] = Threshold; Field[2].InField = 1; Field[2].SizeMin = {h_br!r}; "
               f"Field[2].SizeMax = {h_far!r}; Field[2].DistMin = {float(params['refine_distance_mm'])!r}; "
               f"Field[2].DistMax = {4 * float(params['refine_distance_mm'])!r};")
    out.append("Background Field = 2;")
    out.append("Mesh.MeshSizeExtendFromBoundary = 0; Mesh.MeshSizeFromPoints = 0; Mesh.MeshSizeFromCurvature = 0;")
    out.append("Mesh.ElementOrder = 2; Mesh.SecondOrderLinear = 0;")
    out.append('Physical Surface("ROTOR") = {1};')
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def read_mesh(mesh_inp: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """(node ids, xy (n,2), CPS6 connectivity (m,7): element id + 6 nodes)."""
    text = Path(mesh_inp).read_text(encoding="utf-8")
    nb = text.split("*NODE", 1)[1].split("*", 1)[0]
    rows = np.array([[float(v) for v in ln.split(",")] for ln in nb.strip().splitlines()])
    elems = []
    for blk in text.split("*ELEMENT")[1:]:
        head, body = blk.split("\n", 1)
        if "CPS6" not in head.upper():
            continue
        for ln in body.split("*", 1)[0].strip().splitlines():
            elems.append([int(v) for v in ln.split(",") if v.strip()])
    return rows[:, 0].astype(int), rows[:, 1:3], np.array(elems)


def seat_nodes(geom, ids, xy):
    x0, y0, x1, y1 = (float(v) for v in geom["seat_half"])
    d = np.array([x1 - x0, y1 - y0]); Ls = float(np.hypot(*d)); u = d / Ls
    rel = xy - [x0, y0]
    s = rel @ u
    off = np.abs(rel @ np.array([-u[1], u[0]]))
    on = (off < 1e-4) & (s > -1e-6) & (s < Ls + 1e-6)
    order = np.argsort(s[on])
    return ids[on][order], s[on][order], Ls


def write_deck(geom: dict, params: dict, mesh_inp: Path, deck: Path, with_pocket: bool = True) -> dict:
    ids, xy, elems = read_mesh(mesh_inp)
    a = half_angle(geom)
    ta, L = ANALYSIS_THICKNESS_MM, float(geom["stack_mm"])
    scale = ta / L
    w = float(params["speed_rpm"]) * 2 * math.pi / 60
    lam = geom["lamination"]
    rho = float(params.get("lamination_density_kg_m3", lam["density_kg_m3"])) * 1e-12   # t/mm^3
    E, nu = float(params.get("youngs_modulus_MPa", lam["youngs_modulus_MPa"])), float(lam["poisson_ratio"])
    xsym = ids[np.abs(xy[:, 1]) < TOL]
    n2 = np.array([-math.sin(a), math.cos(a)])
    sym2 = ids[np.abs(xy @ n2) < 1e-6]
    cload, F_mag, nseat = "", np.zeros(2), 0
    if with_pocket:
        sn, s, Ls = seat_nodes(geom, ids, xy)
        if len(sn) < 3 or len(sn) % 2 == 0:
            raise RuntimeError(f"seat has {len(sn)} nodes; expected an odd count (quadratic edges)")
        mag = geom["magnet_half"]
        rho_m = float(geom["magnet"]["density_kg_m3"]) * 1e-12
        if params.get("magnet_mass_g") is not None:
            # client data (a BOM mass per magnet): the effective density that puts that mass on the stack length
            # the load uses (the magnet may be shorter than the stack: revision 5, 83.1 against 83.82 mm)
            rho_m = float(params["magnet_mass_g"]) * 1e-6 / (float(mag["area_mm2"]) * L)
        c = np.array(mag["centroid_mm"], float)
        F_full = rho_m * float(mag["area_mm2"]) * L * w ** 2 * c      # N, whole stack, half pole's magnet
        q = F_full * scale / Ls                                         # N/mm along the seat, analysed layer
        f = np.zeros((len(sn), 2))
        for k in range(0, len(sn) - 2, 2):
            seg = s[k + 2] - s[k]
            f[k] += q * seg / 6; f[k + 1] += q * seg * 4 / 6; f[k + 2] += q * seg / 6
        # 13 significant digits: CalculiX rejected 22-character numbers in *CLOAD (17 digits plus an exponent)
        cload = "*CLOAD\n" + "".join(f"{int(n)}, 1, {float(fx):.12e}\n{int(n)}, 2, {float(fy):.12e}\n"
                                     for n, (fx, fy) in zip(sn, f))
        F_mag, nseat = f.sum(axis=0) / scale, len(sn)

    def nset(name, arr):
        return f"*NSET, NSET={name}\n" + "\n".join(str(int(i)) for i in arr) + "\n"

    ca, sa = math.cos(a), math.sin(a)
    deck.write_text(
        f"*INCLUDE, INPUT={Path(mesh_inp).name}\n" + nset("XSYM", xsym) + nset("SYM2", sym2)
        + f"*TRANSFORM, NSET=SYM2, TYPE=R\n{ca!r}, {sa!r}, 0., {-sa!r}, {ca!r}, 0.\n"
        + f"*MATERIAL, NAME=LAM\n*ELASTIC\n{E!r}, {nu!r}\n*DENSITY\n{rho!r}\n"
        + f"*SOLID SECTION, ELSET=ROTOR, MATERIAL=LAM\n{ta!r}\n"
        + "*BOUNDARY\nXSYM, 2, 2, 0.\nSYM2, 2, 2, 0.\n"
        + f"*STEP\n*STATIC\n*DLOAD\nROTOR, CENTRIF, {w * w!r}, 0., 0., 0., 0., 0., 1.\n" + cload
        + "*NODE FILE, OUTPUT=2D\nU\n*EL FILE, OUTPUT=2D\nS\n"
        + "*NODE PRINT, NSET=XSYM, TOTALS=ONLY\nRF\n*NODE PRINT, NSET=SYM2, TOTALS=ONLY\nRF\n*END STEP\n",
        encoding="utf-8")
    # body force of the analysed sector, scaled back to the whole stack: rho w^2 L * integral of (x, y) dA
    A, Sx, Sy = 0.0, 0.0, 0.0
    idx = {int(n): k for k, n in enumerate(ids)}
    for e in elems:
        p = np.array([xy[idx[n]] for n in e[1:7]])            # corners 0-2, mid-sides 3-5
        # 6-node triangle, straight or curved sides: 3-point rule at the mid-side nodes is exact for the area of a
        # straight-sided element; use the sub-triangle decomposition through the mid-sides for curved sides
        for tri in ((0, 3, 5), (3, 1, 4), (5, 4, 2), (3, 4, 5)):
            q = p[list(tri)]
            ar = 0.5 * ((q[1, 0] - q[0, 0]) * (q[2, 1] - q[0, 1]) - (q[2, 0] - q[0, 0]) * (q[1, 1] - q[0, 1]))
            cx, cy = q.mean(axis=0)
            A += ar; Sx += ar * cx; Sy += ar * cy
    F_body = rho * w ** 2 * L * np.array([Sx, Sy])
    return {"nodes": int(len(ids)), "elements": int(len(elems)), "xsym_nodes": int(len(xsym)),
            "sym2_nodes": int(len(sym2)), "seat_nodes": int(nseat), "analysis_thickness_mm": ta,
            "force_scale": scale, "omega_rad_s": w, "sector_area_mm2": A,
            "body_force_N": F_body.tolist(), "magnet_force_N": F_mag.tolist(),
            "half_angle_rad": a, "inter_pole_normal": n2.tolist()}


def nodal_stress(frd: dict) -> dict:
    S = frd["STRESS"]
    return {int(n): (sxx, syy, sxy) for n, sxx, syy, sxy in zip(S["ids"], S["SXX"], S["SYY"], S["SXY"])}


def linearize(sample_s, srr, stt, srt):
    """Membrane and membrane-plus-bending von Mises (plane stress) along a stress classification line of length t.

    sample_s: positions 0..t; s*: stress components there. Membrane = mean; bending = linear part (ASME VIII-2
    Annex 5-A), evaluated at both surfaces. Returns (membrane von Mises, max surface von Mises of m + b).
    """
    from scipy.integrate import simpson   # exact for the quadratic bending integrand of a linear stress

    s = np.asarray(sample_s, float)
    t = s[-1] - s[0]
    m = {k: simpson(np.asarray(v), x=s) / t for k, v in (("rr", srr), ("tt", stt), ("rt", srt))}
    b = {k: 6 / t ** 2 * simpson(np.asarray(v) * (t / 2 - (s - s[0])), x=s)
         for k, v in (("rr", srr), ("tt", stt), ("rt", srt))}

    def vm(rr, tt, rt):
        return math.sqrt(rr * rr - rr * tt + tt * tt + 3 * rt * rt)
    vm_m = vm(m["rr"], m["tt"], m["rt"])
    vm_mb = max(vm(m["rr"] + sg * b["rr"], m["tt"] + sg * b["tt"], m["rt"] + sg * b["rt"]) for sg in (1, -1))
    return vm_m, vm_mb


def rotating_disk(r, a, b, rho, w, nu):
    """Plane-stress rotating disk with a free central hole (a) and free rim (b): (sigma_r, sigma_theta)."""
    k = (3 + nu) / 8 * rho * w ** 2
    r = np.asarray(r, float)
    return (k * (a * a + b * b - a * a * b * b / r ** 2 - r * r),
            k * (a * a + b * b + a * a * b * b / r ** 2 - (1 + 3 * nu) / (3 + nu) * r * r))
