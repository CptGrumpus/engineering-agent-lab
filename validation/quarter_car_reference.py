"""Independent references for the linear quarter car.

Does not import the model under test (models/quarter_car.py). It shares only
the road definition (excitation/road.py).

1. Transfer functions from road displacement Zr(s), derived by hand from the
   Laplace-transformed equations of motion:

       P(s) = ms s^2 + cs s + ks          (sprung-mass dynamic stiffness)
       Q(s) = mu s^2 + cs s + ks + kt     (unsprung-mass dynamic stiffness)
       C(s) = cs s + ks                   (suspension coupling)
       D(s) = P Q - C^2

       Zs/Zr = kt C / D
       Zu/Zr = kt P / D

   Derived outputs: body acceleration s^2 Zs, suspension travel Zs - Zu,
   tire deflection Zu - Zr (tire load variation = kt (Zu - Zr)).

2. Steady-state RMS of each output for a sum of sinusoids whose frequencies are
   all periodic in the analysis window: RMS^2 = sum_i |H(j w_i)|^2 A_i^2 / 2.

3. Time response to an arbitrary road via the state-space matrix exponential
   (scipy.signal.lsim, first-order hold), with the state matrices assembled here.

4. Eigenvalues (decay rate of free transients).
"""

from __future__ import annotations

import numpy as np
from scipy import signal

from excitation.road import Road, iso8608_sinusoids


def _p(params):
    return (float(params["sprung_mass_kg"]), float(params["unsprung_mass_kg"]),
            float(params["suspension_stiffness_N_per_m"]), float(params["damping_N_s_per_m"]),
            float(params["tire_stiffness_N_per_m"]))


def frequency_response(params: dict, freq_hz) -> dict:
    ms, mu, ks, cs, kt = _p(params)
    s = 2j * np.pi * np.asarray(freq_hz, float)
    P = ms * s**2 + cs * s + ks
    Q = mu * s**2 + cs * s + ks + kt
    C = cs * s + ks
    D = P * Q - C**2
    zs = kt * C / D
    zu = kt * P / D
    return {
        "body_accel": s**2 * zs,          # (m/s^2) per m of road
        "travel": zs - zu,                # m per m
        "tire_deflection": zu - 1.0,      # m per m
    }


def steady_state_rms(params: dict) -> dict:
    """Exact window RMS for the iso8608 sum-of-sinusoids road."""
    ms, mu, ks, cs, kt = _p(params)
    road = iso8608_sinusoids(params)
    h = frequency_response(params, road.freq_hz)
    a2 = road.amp_m**2 / 2.0
    static = (ms + mu) * 9.80665
    return {
        "body_accel_rms_m_per_s2": float(np.sqrt(np.sum(np.abs(h["body_accel"]) ** 2 * a2))),
        "suspension_travel_rms_mm": 1e3 * float(np.sqrt(np.sum(np.abs(h["travel"]) ** 2 * a2))),
        "tire_load_rms_ratio": kt * float(np.sqrt(np.sum(np.abs(h["tire_deflection"]) ** 2 * a2)))
        / static,
    }


def state_space(params: dict):
    """x = [zs, vs, zu, vu], input u = zr."""
    ms, mu, ks, cs, kt = _p(params)
    A = np.array([
        [0, 1, 0, 0],
        [-ks / ms, -cs / ms, ks / ms, cs / ms],
        [0, 0, 0, 1],
        [ks / mu, cs / mu, -(ks + kt) / mu, -cs / mu],
    ])
    B = np.array([[0], [0], [0], [kt / mu]])
    return A, B


def slowest_decay_rate(params: dict) -> float:
    """Smallest |Re(lambda)| over the system eigenvalues [1/s]."""
    A, _ = state_space(params)
    return float(np.min(np.abs(np.linalg.eigvals(A).real)))


def time_response(params: dict, t: np.ndarray, refine: int = 10) -> dict:
    """Response from rest via matrix exponential on a grid `refine` x finer than t."""
    A, B = state_space(params)
    sys = signal.StateSpace(A, B, np.eye(4), np.zeros((4, 1)))
    t_fine = np.linspace(t[0], t[-1], (len(t) - 1) * refine + 1)
    road = Road(params)
    _, _, x = signal.lsim(sys, np.asarray(road.zr(t_fine), float), t_fine, interp=True)
    x = x[::refine]
    return {"zs_m": x[:, 0], "vs_m_per_s": x[:, 1], "zu_m": x[:, 2], "vu_m_per_s": x[:, 3]}


# --------------------------------------------------------------------------- tire lift-off

G = 9.80665


def _liftoff_matrices(params: dict):
    """Augmented LTI systems for the four phases of a (1 - cos) bump with a tire that can
    leave the road: contact or airborne, on the bump or after it.

    State y = [zs, vs, zu, vu, 1, c, s] with c = cos(w t), s = sin(w t) generated by
    their own linear dynamics, so every phase is y' = M y and is solved exactly by
    the matrix exponential. In contact the tire adds kt (zr - zu) with
    zr = h/2 (1 - c) on the bump and 0 after it; airborne, the tire force is zero,
    which in equilibrium coordinates is a constant -W on the wheel (W = (ms + mu) g)."""
    ms, mu, ks, cs, kt = _p(params)
    h = float(params["bump_height_m"])
    V, L = float(params["speed_m_per_s"]), float(params["bump_length_m"])
    w = 2 * np.pi * V / L
    W = (ms + mu) * G
    base = np.zeros((7, 7))
    base[0, 1] = 1.0
    base[1, [0, 1, 2, 3]] = [-ks / ms, -cs / ms, ks / ms, cs / ms]
    base[2, 3] = 1.0
    base[3, [0, 1, 2, 3]] = [ks / mu, cs / mu, -ks / mu, -cs / mu]
    base[5, 6], base[6, 5] = -w, w           # c' = -w s, s' = w c
    M = {}
    for on_bump in (True, False):
        contact = base.copy()
        contact[3, 2] -= kt / mu
        if on_bump:
            contact[3, 4] += kt / mu * h / 2
            contact[3, 5] -= kt / mu * h / 2
        air = base.copy()
        air[3, 4] -= W / mu
        M[("contact", on_bump)], M[("air", on_bump)] = contact, air
    return M, h, L / V, W / kt


def time_response_liftoff(params: dict, t: np.ndarray) -> dict:
    """Exact piecewise-linear response from rest with a tire that can leave the road.

    Within each phase the matrix exponential is exact; phase switches are found by
    bracketing the tire compression delta = W/kt + zr - zu on the output grid and
    solving delta(t) = 0 with Brent's method on the exact solution (to 1e-13 s).
    Returns the series on `t` and the list of (time, 'liftoff' | 'touchdown') events."""
    from scipy.linalg import expm
    from scipy.optimize import brentq

    M, h, T, d0 = _liftoff_matrices(params)
    dt = t[1] - t[0]

    def delta(y, on_bump):
        zr = h / 2 * (y[4] - y[5]) if on_bump else 0.0
        return d0 + zr - y[2]

    y = np.zeros(7)
    y[4], y[5] = 1.0, 1.0
    out = np.empty((len(t), 7))
    out[0] = y
    mode, t_seg, events = "contact", 0.0, []
    k = 0                                     # last grid index already filled
    while k < len(t) - 1:
        t0 = max(t_seg, t[k])                 # start of this piece: a grid point or a phase switch
        y_k = out[k] if t_seg <= t[k] else y_seg_state
        on_bump = t0 < T - 1e-12
        A = M[(mode, on_bump)]
        t_next = t[k + 1]
        # the bump end is a phase boundary too
        t_stop = T if (on_bump and T < t_next - 1e-15) else t_next
        y_end = expm(A * (t_stop - t0)) @ y_k
        g0, g1 = delta(y_k, on_bump), delta(y_end, on_bump)
        switch = (mode == "contact" and g1 < 0 <= g0) or (mode == "air" and g1 > 0 >= g0)
        if switch:
            f = lambda tau: delta(expm(A * (tau - t0)) @ y_k, on_bump)  # noqa: E731
            te = brentq(f, t0, t_stop, xtol=1e-13, rtol=1e-15)
            y_seg_state = expm(A * (te - t0)) @ y_k
            events.append((te, "liftoff" if mode == "contact" else "touchdown"))
            mode, t_seg = ("air" if mode == "contact" else "contact"), te
            continue
        if t_stop < t_next:                    # crossed the bump end inside this step
            y_seg_state, t_seg = y_end, t_stop
            continue
        out[k + 1] = y_end
        t_seg = t_next
        k += 1
    if dt <= 0:
        raise ValueError("time grid must be increasing")
    zr = np.where(t < T, h / 2 * (1 - np.cos(2 * np.pi * t / T)), 0.0)
    return {"zs_m": out[:, 0], "vs_m_per_s": out[:, 1], "zu_m": out[:, 2], "vu_m_per_s": out[:, 3],
            "zr_m": zr, "events": events}
